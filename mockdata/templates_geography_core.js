  function generateGeographyBank(targetCount = 500) {
    const bank = [];
    const baseList = [];

    // 1. 處理原本的「大題組 (basePools)」
    if (typeof basePools !== 'undefined') {
      basePools.forEach(unit => {
        unit.items.forEach(item => {
          baseList.push({
            unitId: unit.unitId,
            unitName: unit.unitName,
            grade: unit.grade,
            t: unit.t,
            item: item
          });
        });
      });
    }

    // 2. 💡 處理你新增的「單行題目 (singleQuestions)」
    if (typeof singleQuestions !== 'undefined') {
      singleQuestions.forEach(item => {
        baseList.push({
          unitId: "misc_single",
          unitName: "綜合單題",
          grade: item.grade || "通用",
          t: item.t || [],  // 單題如果有自己的標籤，就放在這
          item: item        // 直接把單題當作 item 傳入
        });
      });
    }

    if (baseList.length === 0) return bank;

    let idx = 0;
    while (bank.length < targetCount) {
      const entry = baseList[idx % baseList.length];
      const variant = makeVariant(entry.item, {
        unitId: entry.unitId,
        unitName: entry.unitName,
        grade: entry.grade,
        t: entry.t
      });

      bank.push(variant);
      idx++;
    }
    return bank;
  }

